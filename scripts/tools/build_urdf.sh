#!/usr/bin/env bash
# =============================================================================
# build_urdf.sh — 生成仿真用的 URDF（去注释版）
# =============================================================================
# 用途
#   把 piper_with_ros2_control.urdf.xacro 展开成 piper_sim.urdf，并剥离所有
#   XML 注释，结果直接写进源码目录，由 launch 在构建期读取。
#
# 为什么必须去注释？（关键约束，改动前务必读懂）
#   gazebo_ros2_control 读取 robot_description 后，会把整个 URDF 文本拼成
#   一个命令行参数：
#       std::string rb_arg = std::string("robot_description:=") + urdf_string;
#       arguments.push_back(RCL_PARAM_FLAG);
#       arguments.push_back(rb_arg);
#       rcl_parse_arguments(...)
#   rcl 会把该参数值按 YAML 解析。YAML 规则是「冒号+空格」表示键值分隔，
#   因此 XML 注释里只要出现 ": "，就会被当成 YAML 键值对，解析直接失败：
#       [ERROR] parser error Couldn't parse parameter override rule
#   连 xacro 自动生成的头注释都含冒号：
#       "This document was autogenerated by xacro from /path/to/file.xacro"
#
#   已用 C 程序直接调用 rcl_parse_arguments 实测（见 docs/4_输出.md）：
#       注释含 "a: b"   -> FAIL
#       注释含 "a:b"    -> PASS
#       注释含 "x = 1"  -> PASS
#       删除所有注释     -> PASS
#
# 什么时候需要重跑
#   修改了 piper_with_ros2_control.urdf.xacro 之后，必须重跑本脚本，
#   否则 launch 用的还是旧的 piper_sim.urdf。
#
# 用法
#   bash scripts/tools/build_urdf.sh
# =============================================================================
set -eo pipefail

# 注意: 不可使用 `set -u`。ROS 2 Humble 的 setup.bash 会引用未定义变量。
set -o pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WS_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
PKG_DIR="${WS_ROOT}/src/description/classify_description"

# shellcheck disable=SC1091
source /opt/ros/humble/setup.bash

# xacro 里的 $(find classify_description) 需要工作空间在 AMENT_PREFIX_PATH 中。
# 注意: 不能用 `[ -f ... ] && source` 这种写法 —— 当条件不成立时整条命令返回非零，
# 在 set -e 下会直接退出脚本。
if [ -f "${WS_ROOT}/install/setup.bash" ]; then
  source "${WS_ROOT}/install/setup.bash"
else
  echo "✘ 找不到 ${WS_ROOT}/install/setup.bash"
  echo "  请先执行: colcon build --packages-up-to classify_description --symlink-install --executor sequential"
  exit 1
fi

if ! ros2 pkg prefix classify_description > /dev/null 2>&1; then
  echo "✘ ament index 中找不到 classify_description"
  echo "  请先执行: colcon build --packages-up-to classify_description --symlink-install --executor sequential"
  exit 1
fi

URDF_DIR="${PKG_DIR}/urdf"
# 两份输出
#   piper_sim.urdf      file:// 网格路径  -> 给 Gazebo（Classic 不认 package://）
#   piper_sim_rviz.urdf package:// 路径  -> 给 RViz（认 package://，可跨机移植）
OUT_SIM="${URDF_DIR}/piper_sim.urdf"
OUT_RVIZ="${URDF_DIR}/piper_sim_rviz.urdf"
TMP="$(mktemp /tmp/piper_sim_urdf.XXXXXX)"

echo "==> 展开 xacro"
# 先展开，再去注释。sed 的 /<!--/,/-->/d 会删除所有注释块（含 xacro 头注释）。
#
# 注意: controllers_file / initial_positions_file 必须传绝对路径。
#   xacro 会先把 xacro 内部的 $(find classify_description) 展开成绝对路径，
#   若这里传相对路径，两者会被拼接成
#       <urdf目录>/src/description/.../config/xxx.yaml
#   从而报 "No such file or directory"。
PKG_DIR="$(cd "${PKG_DIR}" && pwd)"
URDF_DIR="$(cd "${URDF_DIR}" && pwd)"

# 不用管道: 管道会受 set -e 与上游退出码影响，且错误信息容易丢。
# 先落盘再处理，出错时能直接看到 xacro 的原始 stderr。
RAW="$(mktemp /tmp/piper_sim_raw.XXXXXX)"
trap 'rm -f "${TMP}" "${RAW}"' EXIT

if ! xacro "${URDF_DIR}/piper_with_ros2_control.urdf.xacro" \
           name:=GazeboSystem \
           "controllers_file:=${PKG_DIR}/config/ros2_controllers.yaml" \
           "camera_profile_file:=${PKG_DIR}/config/gemini335.yaml" \
           "initial_positions_file:=${PKG_DIR}/config/gazebo_initial_positions.yaml" \
           > "${RAW}"; then
  echo "✘ xacro 展开失败，原始错误如下："
  head -5 "${RAW}" >&2
  exit 1
fi

# -----------------------------------------------------------------------------
# 两步后处理
#   1) 剥离全部 XML 注释
#   2) package://  ->  file://
# -----------------------------------------------------------------------------
python3 - "${RAW}" "${TMP}" "${PKG_DIR}" <<'PYEOF'
import os
import re
import sys

src, dst, pkg_dir = sys.argv[1], sys.argv[2], sys.argv[3]
with open(src, encoding='utf-8') as f:
    text = f.read()

# 1) 剥离注释
#    用非贪婪正则匹配到第一个 --> ，正是 XML 注释的结束位置。
#    不用 sed 的范围匹配: 它遇到注释正文里的双连字符会提前结束范围，
#    把注释之后的真实标签一起删掉，产出标签不配对的 URDF。
text = re.sub(r'<!--.*?-->', '', text, flags=re.S)

# 2) 网格路径统一替换为占位符
#    Gazebo Classic 不支持 package:// （libgazebo_common.so.11 里只有 model://），
#    RViz 认 package:// 但 Gazebo 不认。若统一用 package://，
#    模型能生成、但 Gazebo 里所有 mesh 静默加载失败，表现为"看不见机械臂"。
#    官方 piper_description_gazebo.xacro 用的正是 file://。
#    做法: 不管 xacro 里写的是哪个包名，统一替换成 __MESH_PREFIX__ 占位符，
#          最后由调用方决定填 file:// 还是 package://。
text = re.sub(r'filename="package://[^/]+/meshes/', 'filename="__MESH_PREFIX__', text)

with open(dst, 'w', encoding='utf-8') as f:
    f.write(text)
PYEOF

# -----------------------------------------------------------------------------
# 校验（任何一项不通过都不允许覆盖目标文件）
# -----------------------------------------------------------------------------
fail=0

if [ ! -s "${TMP}" ]; then
  echo "✘ 展开结果为空"; fail=1
fi

# 必须是合法 XML（用 python 解析，check_urdf 不认识 ros2_control 扩展块）
if [ "${fail}" -eq 0 ] && ! python3 -c "import xml.etree.ElementTree as ET; ET.parse('${TMP}')" 2>/dev/null; then
  echo "✘ XML 解析失败"; fail=1
fi

# 必须含 ros2_control（xacro 宏被调用的证明）
if [ "${fail}" -eq 0 ] && ! grep -q '<ros2_control' "${TMP}"; then
  echo "✘ 缺少 <ros2_control> 块 —— xacro 宏是否忘了调用？"; fail=1
fi

# 必须含 gazebo_ros2_control 插件
if [ "${fail}" -eq 0 ] && ! grep -q 'libgazebo_ros2_control.so' "${TMP}"; then
  echo "✘ 缺少 gazebo_ros2_control 插件声明"; fail=1
fi

# 8 个关节都要有 position 命令接口
if [ "${fail}" -eq 0 ]; then
  n=$(grep -c '<command_interface name="position"/>' "${TMP}" || true)
  if [ "${n}" -ne 8 ]; then
    echo "✘ position 命令接口数量应为 8，实际 ${n}"; fail=1
  fi
fi

# 绝不能有 min/max 钳位（官方文件的致命 bug）
if [ "${fail}" -eq 0 ] && grep -q 'param name="min"' "${TMP}"; then
  echo "✘ 检测到 min/max 钳位 —— 会把 joint2 限制在 57 度"; fail=1
fi

# 不应残留 XML 注释
if [ "${fail}" -eq 0 ] && grep -q '<!--' "${TMP}"; then
  echo "✘ 仍存在 XML 注释（会导致 rcl_parse_arguments 失败）"; fail=1
fi

# TF 链完整性: 每个 joint 的 parent/child 都必须是已存在的 link
# 这一项曾踩坑: 相机 joint 写成 parent link="piper_link6"，
# 但本项目的连杆实际叫 "link6"（官方命名，未加 piper_ 前缀），
# 结果相机挂在一条断链上，机械臂动的时候相机不动，且 Gazebo 不报错。
if [ "${fail}" -eq 0 ]; then
  python3 - "${TMP}" <<'PYEOF'
import sys
import xml.etree.ElementTree as ET

try:
    root = ET.parse(sys.argv[1]).getroot()
except ET.ParseError as e:
    print(f'✘ XML 解析失败: {e}')
    sys.exit(1)

links = {l.get('name') for l in root.iter('link')}
# 注意: root.iter('joint') 也会遍历到 <ros2_control> 内部的 <joint> 元素，
#       那些元素没有 parent/child 标签，必须过滤掉。
#       判据: 顶层 robot 下的 <joint> 才有 parent/child。
robot_joints = [j for j in root.findall('joint')]

bad = []
for j in robot_joints:
    p = j.find('parent')
    c = j.find('child')
    if p is None or c is None:
        bad.append(f"{j.get('name')}: 缺少 parent 或 child")
        continue
    pn, cn = p.get('link'), c.get('link')
    if pn not in links:
        bad.append(f"{j.get('name')}: parent '{pn}' 不存在")
    if cn not in links:
        bad.append(f"{j.get('name')}: child '{cn}' 不存在")

# 根连杆检查。工业机械臂需要固定底座，world_to_base 将其锚定在桌面。
# Gazebo 此时忽略 spawn 位姿，所以 launch 必须在世界原点生成模型。
children = {j.find('child').get('link') for j in robot_joints
            if j.find('child') is not None}
root_links = links - children

anchor = next((j for j in robot_joints if j.get('name') == 'world_to_base'), None)
if anchor is None or anchor.get('type') != 'fixed':
    print('✘ 缺少将机械臂固定到桌面的 world_to_base 关节')
    sys.exit(1)
if anchor.find('parent').get('link') != 'world' or anchor.find('child').get('link') != 'base_link':
    print('✘ world_to_base 必须连接 world → base_link')
    sys.exit(1)
if root_links != {'world'}:
    print(f'✘ 根连杆应唯一且为 world，实际为 {sorted(root_links)}')
    sys.exit(1)

# 孤立 link: 既不是根连杆，也没被任何 joint 当作 child
orphans = [l for l in links if l not in children and l not in root_links]

if bad:
    print('✘ TF 链断裂:')
    for b in bad:
        print(f'    {b}')
    sys.exit(1)

# 相机必须挂在腕部连杆上（eye-in-hand）
cam_joint = [j for j in robot_joints if j.get('name') == 'link6_to_camera']
if not cam_joint:
    print('✘ 缺少 link6_to_camera 关节 —— 腕部相机未挂载')
    sys.exit(1)
if cam_joint[0].find('parent').get('link') != 'link6':
    print('✘ link6_to_camera 的 parent 必须是 link6')
    sys.exit(1)

if orphans:
    print(f'✘ 存在孤立 link（未接入任何关节）: {", ".join(sorted(orphans))}')
    sys.exit(1)

print(f'    TF 链完整: {len(links)} links / {len(robot_joints)} joints，'
      f'根连杆 world，腕部相机已挂在 link6')

# visual / collision 元素结构校验
#   URDF 的 box 用属性写法 size="x y z"，不是子标签 <size>。
#   写错时 xacro 不报错，robot_state_publisher 与 Gazebo 才报
#       "Box shape has no size attribute"
#       "Could not parse visual element for Link [...]"
#   只能在这里提前拦住。
bad_geom = []
for tag in ('visual', 'collision'):
    for el in root.iter(tag):
        box = el.find('geometry/box')
        if box is None:
            continue
        if not box.get('size'):
            bad_geom.append(f'<{tag}> 的 box 缺少 size 属性（URDF 用属性写法，不是 <size> 子标签）')
        elif len(box.get('size').split()) != 3:
            bad_geom.append(f'<{tag}> 的 box size 必须有 3 个数值，实际 "{box.get("size")}"')

if bad_geom:
    print('✘ 几何元素写法错误:')
    for b in sorted(set(bad_geom)):
        print(f'    {b}')
    sys.exit(1)

# material 必须有 name 属性
#   注意: 官方 URDF 用的是 name=""（空字符串），这是合法的。
#         所以不能用 `if not m.get('name')` 判定，
#         必须用 `is None` 区分「属性缺失」与「属性为空」。
bad_mat = []
for tag in ('visual', 'collision'):
    for el in root.iter(tag):
        for m in el.findall('material'):
            if m.get('name') is None:
                bad_mat.append(f'<{tag}> 的 material 缺少 name 属性')
                continue
            if m.find('color') is None and m.find('texture') is None:
                bad_mat.append(
                    f'<{tag}> 的 material "{m.get("name")}" '
                    f'既没有 color 也没有 texture')

if bad_mat:
    print('✘ material 写法错误:')
    for b in sorted(set(bad_mat)):
        print(f'    {b}')
    print('    URDF 的 material 需要 name 属性（空字符串也可以），'
          '颜色用 <color rgba="r g b a"/>')
    print('    注意: <ambient>/<diffuse> 是 Gazebo SDF 的写法，URDF 里无效')
    sys.exit(1)

print('    几何与材质元素写法正确')
PYEOF
  [ $? -ne 0 ] && fail=1
fi

# 占位符数量校验（此时 TMP 里应是 10 个 __MESH_PREFIX__，替换在后面）
if [ "${fail}" -eq 0 ]; then
  n_mesh=$(grep -c '__MESH_PREFIX__' "${TMP}" || true)
  if [ "${n_mesh}" -ne 10 ]; then
    echo "✘ 网格路径占位符应为 10 个（对应 10 个 STL），实际 ${n_mesh}"
    echo "   可能是 xacro 的 mesh 引用写法变了，检查 piper.urdf 里的 package:// 前缀"
    fail=1
  fi
fi

if [ "${fail}" -ne 0 ]; then
  echo "构建失败，未覆盖目标文件"
  exit 1
fi


# Verify calibrated optical chain and actual lens K before replacing outputs.
python3 "${WS_ROOT}/scripts/tools/verify_camera_model.py" --urdf "${TMP}" --output "${WS_ROOT}/log/camera_model_build_check" > /dev/null

# 分别填入两套网格路径
#   Gazebo : file:// + 绝对路径（Gazebo Classic 只认这个）
#   RViz   : package:// + 包名（可跨工作空间移植）
FILE_PREFIX="file://${PKG_DIR}/meshes/"
RVIZ_PREFIX="package://classify_description/meshes/"

sed -e "s|__MESH_PREFIX__|${FILE_PREFIX}|g" "${TMP}" > "${OUT_SIM}"
sed -e "s|__MESH_PREFIX__|${RVIZ_PREFIX}|g" "${TMP}" > "${OUT_RVIZ}"

# RViz 版必须不含 file:// 绝对路径（否则换机器就失效）
if grep -q 'file://' "${OUT_RVIZ}"; then
  echo "✘ RViz 版不应含 file:// 绝对路径"; exit 1
fi
# Gazebo 版必须全部是 file://
if [ "$(grep -c 'package://' "${OUT_SIM}" || true)" -ne 0 ]; then
  echo "✘ Gazebo 版仍有 package:// —— mesh 会静默加载失败"; exit 1
fi

echo "==> 已生成"
echo "    ${OUT_SIM}"
echo "        行数 $(wc -l < "${OUT_SIM}")  |  file:// 网格 $(grep -c 'filename=\"file://' "${OUT_SIM}")  |  package:// $(grep -c 'package://' "${OUT_SIM}" || true)  |  注释 $(grep -c '<!--' "${OUT_SIM}" || true)"
echo "    ${OUT_RVIZ}"
echo "        行数 $(wc -l < "${OUT_RVIZ}")  |  package:// 网格 $(grep -c 'filename=\"package://' "${OUT_RVIZ}")  |  file:// $(grep -c 'file://' "${OUT_RVIZ}" || true)"
echo "        ros2_control $(grep -c '<ros2_control' "${OUT_SIM}")  |  GazeboSystem $(grep -c 'gazebo_ros2_control/GazeboSystem' "${OUT_SIM}")  |  min/max 钳位 $(grep -c 'param name=\"min\"' "${OUT_SIM}" || true)"
echo
echo "下一步: colcon build --packages-up-to classify_description --symlink-install --executor sequential"
